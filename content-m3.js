<p>Отсюда правило подачи результата: <strong>сначала эффект в рублях или процентах, потом доверительный интервал, и только потом p-value</strong>. Продакту нужен первый пункт, вам для защиты вывода — второй, а третий закрывает вопрос «а не показалось ли».</p>

